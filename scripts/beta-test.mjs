import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { prepareBeta } from './beta.mjs';
await mkdir('test-results', { recursive: true });
const root = await mkdtemp(path.resolve('test-results/beta-package-'));
await mkdir(path.join(root, '.output/chrome-mv3'), { recursive: true });
await mkdir(path.join(root, 'test-results'));
const filename = 'streak-fixture-0.1.0-chrome.zip', bytes = Buffer.from('isolated package fixture');
const hash = createHash('sha256').update(bytes).digest('hex');
const head = spawnSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' });
assert.equal(head.status, 0);
const report = { passed: true, revision: head.stdout.trim(), dirty: true, finishedAt: '2026-10-26T00:00:00Z', checks: ['test:beta','test:privacy','test:release'].map(name => ({name,passed:true})) };
await writeFile(path.join(root, 'package.json'), JSON.stringify({ name: 'streak-fixture', version: '0.1.0' }));
await writeFile(path.join(root, '.output', filename), bytes);
await writeFile(path.join(root, '.output/release-sha256.txt'), `${hash}  ${filename}\n`);
await writeFile(path.join(root, '.output/chrome-mv3/manifest.json'), JSON.stringify({version:'0.1.0'}));
await writeFile(path.join(root, 'test-results/release-checks.json'), JSON.stringify(report));
for (const name of ['BETA_START_HERE.md','BETA_LIMITATIONS.md','BETA_FEEDBACK.md']) await writeFile(path.join(root, name), `Fixture ${name}`);
await writeFile(path.join(root, '.env'), 'PRIVATE_FIXTURE_DO_NOT_PACKAGE');
await writeFile(path.join(root, 'test-results/browser-profile.json'), 'PRIVATE_BROWSER_FIXTURE');
const folder = await prepareBeta(root);
assert.deepEqual((await readdir(folder)).sort(), ['BETA_FEEDBACK.md','BETA_LIMITATIONS.md','BETA_START_HERE.md','BUILD_INFO.json','CHECKSUMS.sha256','extension.zip'].sort());
assert.deepEqual(await readFile(path.join(folder,'extension.zip')), bytes);
const info = JSON.parse(await readFile(path.join(folder,'BUILD_INFO.json'),'utf8'));
assert.equal(info.extensionSHA256,hash); assert.equal(info.uncommittedChanges,true); assert.equal(info.cloudConfigured,false);
assert.equal(info.publicLaunchApproved,false); assert.equal(info.participantTesting,'not-recorded');
await writeFile(path.join(root,'.output',filename),'tampered');
await assert.rejects(()=>prepareBeta(root),/ZIP differs/);
await writeFile(path.join(root,'.output',filename),bytes);
await writeFile(path.join(root,'test-results/release-checks.json'),JSON.stringify({...report,passed:false}));
await assert.rejects(()=>prepareBeta(root),/successfully/);
await writeFile(path.join(root,'test-results/release-checks.json'),JSON.stringify({...report,revision:'stale'}));
await assert.rejects(()=>prepareBeta(root),/revision changed/);
await writeFile(path.join(root,'test-results/release-checks.json'),JSON.stringify({...report,checks:[]}));
await assert.rejects(()=>prepareBeta(root),/Missing check/);
console.log('Beta packaging: exact file allowlist, unchanged ZIP/checksum, honest build labels, no env/profile inclusion, and rejected tamper/failed/stale/missing checks passed.');
